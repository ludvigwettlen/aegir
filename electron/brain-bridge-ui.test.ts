import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';
it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('configures explicit workflow folders, preserves opt-in and handles filing/save failures in both setups', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, optimizeDeps: { include: ['react', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime'] }, server: { host: '127.0.0.1', port: 0 }, appType: 'custom' });
  server.middlewares.use('/bridge-fixture', (_req, response) => { response.setHeader('Content-Type', 'text/html'); response.end('<div id="root"></div><script type="module" src="/src/ui/testing/brain-bridge.tsx"></script>'); });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1100, height: 1250 } }); page.setDefaultTimeout(8000);
    const errors: string[] = []; page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
    await page.goto(`${server.resolvedUrls!.local[0]}bridge-fixture`);
    expect(await page.getByLabel('Import external task suggestions').isChecked()).toBe(false);
    await page.getByRole('button', { name: 'Choose import folder', exact: true }).click();
    expect(await page.getByLabel('Import external task suggestions').isChecked()).toBe(false);
    expect(await page.evaluate(() => (window as any).fixture.configurations)).toEqual([]);
    await page.getByLabel('Import external task suggestions').check();
    await page.getByRole('button', { name: 'Choose export folder', exact: true }).click();
    await page.getByLabel('Export task status and notes').check();
    await page.getByRole('button', { name: 'Choose brain filing folder', exact: true }).click();
    await page.getByLabel('Enable per-file brain copies').check();
    await page.evaluate(() => { (window as any).fixture.fail = true; });
    await page.getByRole('button', { name: 'Save workflow settings' }).click();
    await page.getByRole('alert').filter({ hasText: 'folder is unavailable' }).waitFor();
    expect(await page.getByLabel('Intake folder').inputValue()).toContain('/selected/import/');
    await page.evaluate(() => { (window as any).fixture.fail = false; });
    await page.getByRole('button', { name: 'Save workflow settings' }).click();
    await page.getByText('Workflow settings saved.', { exact: true }).waitFor();
    await page.screenshot({ path: '/tmp/aegir-brain-bridge-wide.png', fullPage: true });
    await page.getByRole('button', { name: 'Check now', exact: true }).click();
    await page.getByText(/1 imported · 2 duplicates skipped · 1 rejected/).waitFor();
    await page.getByRole('alert').filter({ hasText: 'Invalid due date' }).waitFor();
    await page.evaluate(() => { (window as any).fixture.allowSave = false; });
    await page.getByRole('button', { name: 'File to brain', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Save the document before filing' }).waitFor();
    expect(await page.evaluate(() => (window as any).fixture.filed)).toEqual([]);
    await page.evaluate(() => { (window as any).fixture.allowSave = true; });
    await page.getByRole('button', { name: 'File to brain', exact: true }).click();
    await page.getByText('Copied to /selected/filing/brain-copy.md', { exact: true }).waitFor();
    expect(await page.evaluate(() => (window as any).fixture.filed)).toEqual([{ id: 'task', path: 'draft.md', kind: 'document' }]);
    await page.evaluate(() => { (window as any).fixture.aegir(); (window as any).fixture.compact(); });
    await expect.poll(() => page.getByLabel('Import external task suggestions').isDisabled()).toBe(true);
    expect(await page.getByLabel('Enable per-file brain copies').isDisabled()).toBe(false);
    expect(await page.getByRole('button', { name: 'Check now', exact: true }).count()).toBe(0);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    expect(await page.locator('main').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
    await page.screenshot({ path: '/tmp/aegir-brain-bridge-compact.png', fullPage: true });
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 45_000);
