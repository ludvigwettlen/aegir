import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium, type Locator } from 'playwright';

it.skipIf(process.env.AEGIR_EDITOR_SMOKE !== '1')('applies independent text sizes, restores settings, and handles failed saves', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/release/**'] } }, appType: 'custom' });
  server.middlewares.use('/typography-test', (_req, response) => {
    response.setHeader('Content-Type', 'text/html');
    response.end('<!doctype html><html><head><meta charset="utf-8"></head><body><div id="root"></div><script type="module" src="/src/ui/testing/typography.tsx"></script></body></html>');
  });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen();
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1100, height: 1000 } });
    page.setDefaultTimeout(5000);
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${server.resolvedUrls!.local[0]}typography-test`);
    const size = (target: Locator) => target.evaluate(el => parseFloat(getComputedStyle(el).fontSize));
    const appSize = page.getByRole('combobox', { name: 'App text size', exact: true });
    const editorSize = page.getByRole('combobox', { name: 'Markdown text size', exact: true });
    const scratchSize = page.getByRole('combobox', { name: 'Scratchpad text size', exact: true });
    const editor = page.locator('[data-document-sample]');
    const scratch = page.getByRole('textbox', { name: 'Document scratchpad' });
    await scratch.fill('Keep these notes');
    expect(await size(editor.locator('p'))).toBe(14);
    expect(await size(scratch)).toBe(13);
    const navigationSize = await size(page.locator('.ws-nav-item'));
    const change = async (control: Locator, value: string) => {
      await control.selectOption(value);
      await expect.poll(() => control.isEnabled()).toBe(true);
      expect(await control.inputValue()).toBe(value);
    };
    await change(appSize, '130');
    expect(await size(page.locator('.ws-message-text'))).toBeCloseTo(18.2);
    expect(await size(page.locator('.ws-nav-item'))).toBeCloseTo(navigationSize * 1.3);
    expect(await size(page.locator('.ws-task-title'))).toBeCloseTo(17.55);
    expect(await size(editor.locator('p'))).toBe(14);
    expect(await size(scratch)).toBe(13);
    await change(editorSize, '24');
    expect(await size(editor.locator('p'))).toBe(24);
    expect(await size(editor.locator('td'))).toBe(24);
    expect(await size(editor.locator('h1'))).toBeCloseTo(32 * 24 / 14, 2);
    expect(await size(page.locator('[aria-label="Markdown editor font preview"] p').first())).toBe(24);
    expect(await size(scratch)).toBe(13);
    await change(scratchSize, '20');
    expect(await size(scratch)).toBe(20);
    expect(await size(page.locator('.ws-scratchpad-preview p'))).toBe(20);
    expect(await scratch.innerText()).toBe('Keep these notes');
    await change(page.getByRole('combobox', { name: 'Markdown editor font', exact: true }), 'lora');
    expect(await editor.evaluate(el => getComputedStyle(el).fontFamily)).toContain('Lora');
    await page.reload();
    await appSize.waitFor();
    expect(await appSize.inputValue()).toBe('130');
    expect(await editorSize.inputValue()).toBe('24');
    expect(await scratchSize.inputValue()).toBe('20');
    expect(await size(scratch)).toBe(20);
    await page.evaluate(() => { (window as any).failTypography = true; });
    await appSize.selectOption('90');
    await expect.poll(() => page.getByRole('alert').innerText()).toContain('Could not save');
    expect(await appSize.inputValue()).toBe('130');
    expect(await size(page.locator('.ws-message-text'))).toBeCloseTo(18.2);
    await page.evaluate(() => { (window as any).failTypography = false; });
    await page.setViewportSize({ width: 900, height: 1000 });
    await page.locator('.page-scroll').evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: '/tmp/aegir-font-sizes.png', fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'Reset to default' }).click();
    await expect.poll(() => editorSize.inputValue()).toBe('14');
    expect(await appSize.inputValue()).toBe('100');
    expect(await scratchSize.inputValue()).toBe('13');
    expect(await size(editor.locator('p'))).toBe(14);
    expect(await size(scratch)).toBe(13);
    expect(await scratch.innerText()).toBe('Keep these notes');
    expect(await page.getByRole('combobox', { name: 'Markdown editor font', exact: true }).inputValue()).toBe('inter');
    await page.setViewportSize({ width: 460, height: 800 });
    await page.locator('.page-scroll').evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: '/tmp/aegir-font-sizes-compact.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 60000);
