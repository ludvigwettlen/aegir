    const head = page.locator('.ws-conversation-head');
    expect(await head.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: '/tmp/aegir-task-header-compact.png' });
    await page.goto(`${url}?files=0`); await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    expect(await page.locator('.ws-task-notes-preview').textContent()).toBe('Add context…');
    await page.getByRole('button', { name: 'Files', exact: true }).click();
    await page.getByText('No Markdown files in this workspace yet.', { exact: true }).waitFor();
    await page.goto(`${url}?failList`); await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Documents unavailable' }).waitFor();
    await page.goto(`${url}?notes&files=1`); await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    await page.setViewportSize({ width: 1400, height: 900 });
    await page.screenshot({ path: '/tmp/aegir-task-header-summary.png' });
    await page.goto(`${server.resolvedUrls!.local[0]}design/mockups/task-detail-iterations.html`);
    await page.getByRole('tab', { name: 'Context · 1 file' }).click();
