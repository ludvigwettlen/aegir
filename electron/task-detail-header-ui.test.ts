    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    const title = page.getByRole('textbox', { name: 'Task title', exact: true });
    expect(await title.evaluate(el => el.scrollHeight <= el.clientHeight + 2)).toBe(true);
    expect(await title.evaluate(el => el.clientHeight)).toBeGreaterThan(40);
    const notes = page.getByRole('textbox', { name: 'Task notes', exact: true });
    expect(await notes.isVisible()).toBe(false);
    const summary = page.locator('.ws-task-notes-disclosure summary');
    await summary.focus(); await page.keyboard.press('Enter');
    await notes.fill('Updated context\n\nKeep the follow-up questions.');
    await summary.click();
    expect(await page.locator('.ws-task-notes-preview').textContent()).toContain('Updated context');
    await summary.click(); expect(await notes.inputValue()).toContain('Updated context'); await summary.click();
    await title.fill('A title edited with the keyboard'); await title.press('Enter');
    expect(await title.inputValue()).toBe('A title edited with the keyboard');
    await expect.poll(() => page.locator('[data-keyboard-current]').evaluate(el => el === document.activeElement)).toBe(true);
    await title.fill('Unsaved replacement'); await title.press('Escape');
    await expect.poll(() => title.inputValue()).toBe('A title edited with the keyboard');
    await expect.poll(() => page.locator('[data-keyboard-current]').evaluate(el => el === document.activeElement)).toBe(true);
    await page.keyboard.press('n');
    expect(await notes.isVisible()).toBe(true);
    expect(await notes.evaluate(el => el === document.activeElement)).toBe(true);
    await summary.click();
    expect(await page.locator('.ws-document-preview small, .ws-document-preview time').count()).toBe(0);
    await page.getByRole('button', { name: 'Copy chat transcript', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Chat transcript copied.' }).waitFor();
    await page.getByRole('button', { name: 'Files', exact: true }).click();
    expect(await page.locator('.ws-document-picker small').count()).toBe(6);
    await page.getByRole('button', { name: 'Close document picker' }).click();
    await page.getByRole('button', { name: 'Repeat task', exact: true }).click();
    await page.getByRole('dialog', { name: 'Repeat task' }).waitFor(); await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Fullscreen task', exact: true }).click();
    await page.screenshot({ path: '/tmp/aegir-task-header-fullscreen.png' });
    await page.getByRole('button', { name: 'Exit fullscreen task', exact: true }).click();
    await page.getByRole('button', { name: 'Open pm-level-boundaries-proposal.md', exact: true }).click();
    await page.getByRole('button', { name: 'Back to list', exact: true }).click();
    expect(await title.evaluate(el => el.scrollHeight <= el.clientHeight + 2)).toBe(true);
    await page.setViewportSize({ width: 900, height: 650 }); await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.evaluate(() => document.documentElement.style.setProperty('--ds-system-text-scale', '1.3'));
