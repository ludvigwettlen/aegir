import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';
it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('supports priorities, fullscreen, attachments, comment batches and opt-in review without replacing the editor', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, optimizeDeps: { include: ['react', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime'] }, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/release/**'] } }, appType: 'custom' });
  server.middlewares.use('/integration-test', (_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<div id="root"></div><script type="module" src="/src/ui/testing/legolas-integration.tsx"></script>'); });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1400, height: 900 } }); page.setDefaultTimeout(10000);
    const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(`${server.resolvedUrls!.local[0]}integration-test`);
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    const row = page.locator('[data-task-row]'); await row.focus(); await page.keyboard.press('1');
    await expect.poll(() => page.getByLabel('Task priority', { exact: true }).inputValue()).toBe('1');
    await page.keyboard.press('0'); await expect.poll(() => page.getByLabel('Task priority', { exact: true }).inputValue()).toBe('');
    await page.locator('.ws-task-options > summary').click();
    await page.getByLabel('Task priority', { exact: true }).selectOption('2'); expect(await row.getByText('P2').count()).toBe(1);
    await page.getByRole('button', { name: 'Fullscreen task', exact: true }).click();
    expect(await page.locator('.ws-task-list').isVisible()).toBe(false);
    expect(await page.locator('.ws-sidebar').isVisible()).toBe(false);
    const outer = await page.locator('.ws-tasks').boundingBox(), detail = await page.getByRole('complementary', { name: 'Task detail' }).boundingBox();
    expect(detail!.width).toBeGreaterThan(outer!.width - 4);
    await page.screenshot({ path: '/tmp/aegir-integration-task.png' });
    await page.getByRole('button', { name: 'Exit fullscreen task', exact: true }).click(); expect(await page.locator('.ws-task-list').isVisible()).toBe(true);
    // Files can be dropped anywhere in the conversation, then removed before sending.
    await page.locator('.ws-thread').evaluate(element => {
      const transfer = new DataTransfer(); transfer.items.add(new File(['notes'], 'dropped.txt', { type: 'text/plain' }));
      element.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }));
    });
    await page.getByRole('button', { name: 'Remove attachment dropped.txt', exact: true }).click();
    const upload = page.locator('input[type="file"]');
    await upload.setInputFiles({ name: 'brief.pdf', mimeType: 'application/pdf', buffer: Buffer.from('test document') });
    const pending = page.getByLabel('Pending attachments'); await pending.getByText('brief.pdf', { exact: false }).waitFor();
    const message = page.getByRole('textbox', { name: 'Message', exact: true }); await message.fill('Review this attachment');
    await page.evaluate(() => { (window as any).fixtureActions.failSend = true; });
    await page.getByRole('button', { name: 'Send', exact: true }).click(); await page.getByText('Message rejected', { exact: false }).waitFor();
    expect(await message.inputValue()).toBe('Review this attachment'); expect(await pending.count()).toBe(1);
    await page.evaluate(() => { (window as any).fixtureActions.failSend = false; });
    await page.getByRole('button', { name: 'Send', exact: true }).click(); await expect.poll(() => pending.count()).toBe(0);
    expect(await page.evaluate(() => (window as any).fixtureActions.sent[0])).toEqual({ text: 'Review this attachment', paths: ['/mock/attachments/brief.pdf'] });
    await page.getByRole('button', { name: 'Open pm-level-boundaries-proposal.md', exact: true }).click();
    expect(await page.getByRole('button', { name: 'Review in browser', exact: true }).count()).toBe(0);
    const prose = page.getByRole('textbox', { name: 'Document', exact: true });
    await page.getByRole('button', { name: 'Typewriter mode', exact: true }).click(); expect(await page.locator('.ws-document-typewriter').count()).toBe(1);
    await page.getByRole('button', { name: 'Chat', exact: true }).click();
    expect(await page.getByRole('navigation', { name: 'Conversation documents' }).isVisible()).toBe(true);
    await page.getByRole('button', { name: 'Outline and notes', exact: true }).click();
    await page.getByRole('radio', { name: 'Comments', exact: true }).click();
    const send = page.getByRole('button', { name: 'Send 2 comments', exact: true }); await send.waitFor();
    // A save failure must leave the annotations and the pending batch intact.
    await page.evaluate(() => { (window as any).fixtureActions.failSave = true; });
    await prose.press('ControlOrMeta+End'); await prose.press('Enter'); await prose.pressSequentially('Direct edit');
    await send.click(); await page.getByText('Save the document before sending comments.', { exact: false }).waitFor();
    expect(await send.isEnabled()).toBe(true);
    await page.evaluate(() => { (window as any).fixtureActions.failSave = false; (window as any).fixtureActions.failSend = true; });
    await send.click(); await page.getByText('Message rejected', { exact: false }).waitFor(); expect(await send.isEnabled()).toBe(true);
    await page.evaluate(() => { (window as any).fixtureActions.failSend = false; });
    await send.click(); await page.getByRole('button', { name: 'Send 0 comments', exact: true }).waitFor();
    expect(await page.getByText('Submitted · saved in conversation', { exact: true }).count()).toBe(2);
    expect(await page.evaluate(() => (window as any).fixtureActions.files[0].content)).toContain('aegir:comment:');
    await page.screenshot({ path: '/tmp/aegir-integration-comments.png' });
    await page.getByRole('button', { name: 'Back to list', exact: true }).click();
    await page.getByRole('button', { name: 'Search tasks and commands', exact: true }).click();
    await page.getByRole('combobox', { name: 'Search tasks and commands' }).fill('Settings');
    await page.getByRole('option', { name: /^Settings/ }).click();
    await page.getByRole('button', { name: 'Browser & review', exact: true }).click();
    await page.getByRole('button', { name: 'Enable browser review', exact: true }).click();
    await page.getByRole('button', { name: 'Disable browser review', exact: true }).waitFor();
    await page.getByRole('button', { name: /Back to workspace/ }).click();
    await page.getByRole('button', { name: 'Open pm-level-boundaries-proposal.md', exact: true }).click();
    await page.getByRole('button', { name: 'Review in browser', exact: true }).click();
    await expect.poll(() => page.evaluate(() => (window as any).fixtureActions.reviews.length)).toBe(1);
    expect(await prose.isVisible()).toBe(true);
    await page.setViewportSize({ width: 900, height: 650 }); await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.getByRole('button', { name: 'Chat', exact: true }).click();
    const outline = page.getByRole('button', { name: 'Outline and notes', exact: true });
    if (await outline.getAttribute('aria-expanded') !== 'true') await outline.click();
    await page.getByRole('radio', { name: 'Comments', exact: true }).click();
    await page.screenshot({ path: '/tmp/aegir-integration-compact.png' });
    const panel = await page.getByRole('complementary', { name: 'Document outline and notes' }).boundingBox(); expect(panel!.x).toBeGreaterThanOrEqual(0); expect(panel!.x + panel!.width).toBeLessThanOrEqual(900);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 90000);
