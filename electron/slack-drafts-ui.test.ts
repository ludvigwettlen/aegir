import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';
it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('edits Slack drafts, selects recipients, recovers conflicts and sends with one click in compact and wide panes', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, optimizeDeps: { include: ['react', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime'] }, server: { host: '127.0.0.1', port: 0 }, appType: 'custom' });
  server.middlewares.use('/slack-fixture', (_req, response) => { response.setHeader('Content-Type', 'text/html'); response.end('<div id="root"></div><script type="module" src="/src/ui/testing/slack-drafts.tsx"></script>'); });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1100, height: 900 } }); page.setDefaultTimeout(8000);
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${server.resolvedUrls!.local[0]}slack-fixture`);
    const footer = page.getByRole('checkbox', { name: 'Include “Sent using Aegir” footer' });
    expect(await footer.isChecked()).toBe(true);
    await page.getByLabel('Message footer', { exact: true }).waitFor();
    await footer.focus(); await page.keyboard.press('Space');
    expect(await page.getByLabel('Message footer', { exact: true }).count()).toBe(0);
    await page.getByLabel('Slack message').fill('My revised Slack message.');
    await page.reload(); expect(await page.getByLabel('Slack message').inputValue()).toBe('My revised Slack message.');
    expect(await footer.isChecked()).toBe(false);
    await page.evaluate(() => { (window as any).fixture.fail = true; });
    await page.getByRole('button', { name: 'Save draft', exact: true }).click(); await page.getByRole('alert').filter({ hasText: 'Could not save' }).waitFor();
    await page.evaluate(() => { (window as any).fixture.fail = false; });
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    expect(await page.evaluate(() => (window as any).fixture.draft.includeFooter)).toBe(false);
    await footer.check();
    await page.screenshot({ path: '/tmp/aegir-slack-draft-wide.png' });
    await page.getByLabel('Slack message').fill('Keep my local edits');
    await page.evaluate(() => { (window as any).fixture.conflict(); });
    await page.getByRole('button', { name: 'Discard local edits and reload' }).waitFor();
    expect(await page.getByLabel('Slack message').inputValue()).toBe('Keep my local edits');
    expect(await page.getByRole('button', { name: 'Send', exact: true }).isDisabled()).toBe(true);
    await page.getByRole('button', { name: 'Discard local edits and reload' }).click();
    expect(await footer.isChecked()).toBe(false);
    await page.getByRole('button', { name: 'Change recipient' }).click();
    await page.getByLabel('Search Slack').fill('Sam');
    await page.getByRole('button', { name: 'Search', exact: true }).click();
    await page.getByRole('button', { name: '@Sam Lee · sam@example.com' }).click();
    await page.getByText('@Sam Lee', { exact: true }).waitFor();
    expect(await page.getByText('Reply in thread', { exact: true }).count()).toBe(0);
    await page.getByLabel('Slack message').fill('Hello Sam, here is the plan.');
    await page.evaluate(() => { (window as any).fixture.compact(); });
    await expect.poll(() => page.locator('main').evaluate(element => element.clientWidth)).toBe(430);
    await page.emulateMedia({ reducedMotion: 'reduce' }); await page.screenshot({ path: '/tmp/aegir-slack-draft-compact.png' });
    expect(await page.locator('main').evaluate(element => element.scrollWidth <= 430)).toBe(true);
    await page.getByRole('button', { name: 'Send', exact: true }).focus(); await page.keyboard.press('Enter');
    await page.getByText('Sending…', { exact: true }).waitFor();
    expect(await page.getByLabel('Slack message').isDisabled()).toBe(true);
    expect(await footer.isDisabled()).toBe(true);
    expect(await page.getByRole('button', { name: 'Approve', exact: true }).count()).toBe(0);
    await page.getByText('Slack confirmed sending.', { exact: true }).waitFor();
    expect(await page.evaluate(() => (window as any).fixture.sendCalls)).toEqual([{ id: 'slack-test', revision: 5, fields: { destination: 'U234567', threadTs: '', text: 'Hello Sam, here is the plan.', includeFooter: false } }]);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 45_000);
