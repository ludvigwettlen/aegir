import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';

it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('opens the task conversation and invokes scoped skills with recoverable drafts', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, optimizeDeps: { include: ['react', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime'] }, server: { host: '127.0.0.1', port: 0, watch: { ignored: ['**/release/**'] } }, appType: 'custom' });
  server.middlewares.use('/task-commands', (_req, response) => {
    response.setHeader('Content-Type', 'text/html');
    response.end('<div id="root"></div><script type="module" src="/src/ui/testing/task-commands.tsx"></script>');
  });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1400, height: 900 } }); page.setDefaultTimeout(5000);
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${server.resolvedUrls!.local[0]}task-commands`);
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    const userMessage = page.locator('[data-message-role="user"]');
    const agentMessage = page.locator('[data-message-role="agent"]');
    await agentMessage.waitFor();
    const divider = page.getByRole('separator', { name: 'Resize task details' });
    const paneWidth = () => page.locator('.ws-task-detail').evaluate(element => element.getBoundingClientRect().width);
    const initialWidth = await paneWidth();
    const handle = (await divider.boundingBox())!;
    await page.mouse.move(handle.x + handle.width / 2, handle.y + 200);
    await page.mouse.down();
    await page.mouse.move(handle.x + handle.width / 2 - 160, handle.y + 200, { steps: 8 });
    await page.mouse.up();
    expect(await paneWidth()).toBe(initialWidth + 160);
    await divider.press('ArrowLeft');
    expect(await paneWidth()).toBe(initialWidth + 170);
    await divider.press('Shift+ArrowRight');
    const chosenWidth = initialWidth + 120;
    expect(await paneWidth()).toBe(chosenWidth);
    expect(await divider.evaluate(element => element === document.activeElement)).toBe(true);
    await page.screenshot({ path: '/tmp/aegir-task-resize-wide.png' });
    await page.setViewportSize({ width: 900, height: 900 });
    await expect.poll(paneWidth).toBe(chosenWidth);
    expect(await page.locator('.ws-task-list-clip').evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThanOrEqual(24);
    expect(await page.locator('.ws-task-list').evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThanOrEqual(280);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: '/tmp/aegir-task-resize-compact.png' });
    await page.setViewportSize({ width: 1400, height: 900 });
    await page.waitForFunction(width => document.querySelector('.ws-task-detail')!.getBoundingClientRect().width === width, chosenWidth);
    await page.reload();
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    expect(await paneWidth()).toBe(chosenWidth);
    await divider.press('Home');
    expect(await divider.getAttribute('aria-valuenow')).toBe(await divider.getAttribute('aria-valuemax'));
    await divider.press('End');
    expect(await divider.getAttribute('aria-valuenow')).toBe(await divider.getAttribute('aria-valuemin'));
    await divider.press('Enter');
    expect(await paneWidth()).toBe(initialWidth);
    await divider.press('ArrowLeft');
    await divider.dblclick();
    expect(await paneWidth()).toBe(initialWidth);
    await page.mouse.move(0, 0);
    const userCopy = userMessage.getByRole('button', { name: 'Copy message', exact: true });
    expect(await userCopy.evaluate(element => getComputedStyle(element).opacity)).toBe('0');
    await userMessage.hover();
    expect(await userCopy.evaluate(element => getComputedStyle(element).opacity)).toBe('1');
    expect(await userMessage.locator('.ws-copy-message').evaluate(element => getComputedStyle(element).justifyContent)).toBe('flex-end');
    expect(await agentMessage.locator('.ws-copy-message').evaluate(element => getComputedStyle(element).justifyContent)).not.toBe('flex-end');
    await page.mouse.move(0, 0); await userCopy.focus();
    expect(await userCopy.evaluate(element => getComputedStyle(element).opacity)).toBe('1');
    await page.locator('.ws-task-notes-disclosure > summary').click();
    const notes = page.getByRole('textbox', { name: 'Task notes' });
    expect(await notes.evaluate(element => Math.abs(element.getBoundingClientRect().width - (element.closest('.ws-task-detail')!.getBoundingClientRect().width - 41)) < 2)).toBe(true);
    await page.screenshot({ path: '/tmp/aegir-chat-controls.png' });
    const composer = page.getByRole('textbox', { name: 'Message', exact: true });
    await composer.fill('/');
    await page.getByRole('option', { name: '/research' }).waitFor();
    expect(await page.getByRole('option', { name: '/writing' }).count()).toBe(0);
    await page.screenshot({ path: '/tmp/aegir-task-skills.png' });
    await page.keyboard.press('Enter');
    await composer.fill('Compare competitors');
    await page.evaluate(() => { (window as any).fixture.fail = true; });
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.waitForFunction(() => (document.querySelector('[aria-label="Message"]') as HTMLTextAreaElement)?.value === 'Compare competitors');
    expect(await page.getByRole('button', { name: 'Remove skill research' }).count()).toBe(1);
    await page.evaluate(() => { (window as any).fixture.fail = false; });
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.waitForFunction(() => (window as any).fixture.sent.length === 1);
    expect(await page.evaluate(() => (window as any).fixture.sent[0])).toContain('$skill:11111111-1111-4111-8111-111111111111');
    expect(await composer.inputValue()).toBe('');
    await page.getByRole('button', { name: 'Thread in #Team' }).click();
    expect(await page.getByRole('button', { name: 'Tasks · 1' }).getAttribute('aria-pressed')).toBe('true');
    await page.locator('.ws-thread-item.selected').waitFor();
    expect(await page.locator('.ws-thread-item.selected').innerText()).toContain('Research brief');
    expect(await composer.count()).toBe(1);
    await composer.fill('@Saga /w');
    await page.getByRole('option', { name: '/writing' }).waitFor();
    await page.keyboard.press('Tab');
    await composer.fill('Different recipient');
    await page.getByText('A selected skill is unavailable', { exact: false }).waitFor();
    expect(await page.getByRole('button', { name: 'Send', exact: true }).isDisabled()).toBe(true);
    await page.getByRole('button', { name: 'Remove skill writing' }).click();
    await composer.fill('/missing'); await page.keyboard.press('Escape');
    expect(await composer.inputValue()).toBe('/missing');
    expect(await composer.evaluate(element => element === document.activeElement)).toBe(true);
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    await page.locator('[data-task-row]').focus(); await page.keyboard.press('Shift+A');
    await page.locator('.ws-thread-item.selected').waitFor();
    await page.setViewportSize({ width: 950, height: 800 });
    await composer.fill('/');
    await page.getByRole('listbox', { name: 'Skills' }).waitFor();
    await page.screenshot({ path: '/tmp/aegir-group-skills.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.goto(`${server.resolvedUrls!.local[0]}task-commands?failSkills`);
    await composer.fill('/');
    await page.getByText('Could not load skills.', { exact: false }).waitFor();
    await page.evaluate(() => { (window as any).fixture.failSkills = false; });
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.getByRole('option', { name: '/research' }).waitFor();
    await page.goto(`${server.resolvedUrls!.local[0]}task-commands?loading`);
    await composer.fill('/');
    await page.getByText('Loading skills…', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    expect(await page.getByRole('listbox').count()).toBe(0);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 60000);
