import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';

it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('opens the task conversation and invokes scoped skills with recoverable drafts', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, server: { host: '127.0.0.1', port: 0 }, appType: 'custom' });
  server.middlewares.use('/task-commands', (_req, response) => {
    response.setHeader('Content-Type', 'text/html');
    response.end('<div id="root"></div><script type="module" src="/src/ui/testing/task-commands.tsx"></script>');
  });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1400, height: 900 } }); page.setDefaultTimeout(5000);
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${server.resolvedUrls!.local[0]}task-commands`);
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    const composer = page.getByRole('textbox', { name: 'Message', exact: true });
    await composer.fill('/');
    await page.getByRole('option', { name: '/research' }).waitFor();
    expect(await page.getByRole('option', { name: '/writing' }).count()).toBe(0);
    await page.screenshot({ path: '/tmp/aegir-task-skills.png' });
    await page.keyboard.press('Enter');
    await composer.fill('Compare competitors');
    await page.evaluate(() => { (window as any).fixture.fail = true; });
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.waitForFunction(() => (document.querySelector('[aria-label="Message"]') as HTMLTextAreaElement)?.value === 'Compare competitors');
    expect(await page.getByRole('button', { name: 'Remove skill research' }).count()).toBe(1);
    await page.evaluate(() => { (window as any).fixture.fail = false; });
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await page.waitForFunction(() => (window as any).fixture.sent.length === 1);
    expect(await page.evaluate(() => (window as any).fixture.sent[0])).toContain('$skill:11111111-1111-4111-8111-111111111111');
    expect(await composer.inputValue()).toBe('');
    await page.getByRole('button', { name: 'Thread in #Team' }).click();
    expect(await page.getByRole('button', { name: 'Tasks · 1' }).getAttribute('aria-pressed')).toBe('true');
    await page.locator('.ws-thread-item.selected').waitFor();
    expect(await page.locator('.ws-thread-item.selected').innerText()).toContain('Research brief');
    expect(await composer.count()).toBe(1);
    await composer.fill('@Saga /w');
    await page.getByRole('option', { name: '/writing' }).waitFor();
    await page.keyboard.press('Tab');
    await composer.fill('Different recipient');
    await page.getByText('A selected skill is unavailable', { exact: false }).waitFor();
    expect(await page.getByRole('button', { name: 'Send', exact: true }).isDisabled()).toBe(true);
    await page.getByRole('button', { name: 'Remove skill writing' }).click();
    await composer.fill('/missing'); await page.keyboard.press('Escape');
    expect(await composer.inputValue()).toBe('/missing');
    expect(await composer.evaluate(element => element === document.activeElement)).toBe(true);
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    await page.locator('[data-task-row]').focus(); await page.keyboard.press('Shift+A');
    await page.locator('.ws-thread-item.selected').waitFor();
    await page.setViewportSize({ width: 950, height: 800 });
    await composer.fill('/');
    await page.getByRole('listbox', { name: 'Skills' }).waitFor();
    await page.screenshot({ path: '/tmp/aegir-group-skills.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.goto(`${server.resolvedUrls!.local[0]}task-commands?failSkills`);
    // A reload starts on Today; the fixture task is undated and waiting for review.
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    await composer.fill('/');
    await page.getByText('Could not load skills.', { exact: false }).waitFor();
    await page.evaluate(() => { (window as any).fixture.failSkills = false; });
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.getByRole('option', { name: '/research' }).waitFor();
    await page.goto(`${server.resolvedUrls!.local[0]}task-commands?loading`);
    await page.getByRole('button', { name: 'Needs you', exact: true }).click();
    await composer.fill('/');
    await page.getByText('Loading skills…', { exact: true }).waitFor();
    await page.keyboard.press('Escape');
    expect(await page.getByRole('listbox').count()).toBe(0);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 60000);
