import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';
it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('assigns and tags people with private notes excluded, preserves failures and works in compact layouts', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, server: { host: '127.0.0.1', port: 0 }, appType: 'custom' });
  server.middlewares.use('/delegation', (_req, res) => { res.setHeader('Content-Type', 'text/html'); res.end('<div id="root"></div><script type="module" src="/src/ui/testing/delegation.tsx"></script>'); });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 900, height: 650 } }); page.setDefaultTimeout(7000);
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${server.resolvedUrls!.local[0]}delegation`);
    await page.getByRole('button', { name: 'Assign to person', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Assign to person' });
    expect(await dialog.textContent()).not.toContain('PRIVATE NOTES');
    expect(await page.getByRole('button', { name: 'Assign in Notion' }).isDisabled()).toBe(true);
    await page.getByRole('textbox', { name: 'Assignee', exact: true }).fill('Mal');
    await page.getByRole('group', { name: 'Assignee results' }).getByRole('button').click();
    await page.getByRole('textbox', { name: 'Tagged people', exact: true }).fill('Mal');
    await page.getByRole('group', { name: 'Tagged people results' }).getByRole('button').click();
    await page.getByRole('textbox', { name: 'Shared brief' }).fill('Please review the launch plan.');
    await page.evaluate(() => { (window as any).fixture.fail = true; });
    await page.getByRole('button', { name: 'Assign in Notion' }).click();
    await page.getByRole('alert').filter({ hasText: 'Notion is unavailable' }).waitFor();
    expect(await page.getByRole('textbox', { name: 'Shared brief' }).inputValue()).toBe('Please review the launch plan.');
    await page.evaluate(() => { (window as any).fixture.fail = false; (window as any).fixture.delay = 300; });
    await page.screenshot({ path: '/tmp/aegir-delegation-dialog.png' });
    await page.getByRole('button', { name: 'Assign in Notion' }).click();
    await page.getByRole('button', { name: 'Publishing…' }).waitFor(); await page.keyboard.press('Escape'); expect(await dialog.isVisible()).toBe(true);
    await dialog.waitFor({ state: 'hidden' });
    expect(await page.getByRole('button', { name: 'Assigned to Malcolm Burenstam Linder' }).isVisible()).toBe(true);
    await page.getByRole('combobox', { name: 'Shared status' }).selectOption('Ready for review');
    await page.getByRole('button', { name: 'Update status' }).click();
    await page.getByRole('button', { name: 'Refresh', exact: true }).waitFor();
    await expect.poll(() => page.getByRole('button', { name: 'Update status' }).isDisabled()).toBe(true);
    expect(await page.evaluate(() => (window as any).fixture.calls.length)).toBe(1);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.locator('main').evaluate(el => { el.style.width = '340px'; el.style.boxSizing = 'border-box'; });
    expect(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: '/tmp/aegir-delegation-compact.png' });
    await page.getByRole('button', { name: 'Assigned to Malcolm Burenstam Linder' }).click();
    await page.getByRole('dialog').waitFor(); await page.screenshot({ path: '/tmp/aegir-delegation-dialog-verified.png' }); await page.keyboard.press('Escape');
    await expect.poll(() => page.getByRole('button', { name: 'Assigned to Malcolm Burenstam Linder' }).evaluate(el => el === document.activeElement)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 40_000);
