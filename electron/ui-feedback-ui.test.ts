import { expect, it } from 'vitest';
import { createServer } from 'vite';
import { chromium } from 'playwright';

it.skipIf(process.env.AEGIR_UI_SMOKE !== '1')('selects without activating controls, recovers failed saves and reviews feedback at compact sizes', async () => {
  const server = await createServer({ configFile: false, esbuild: { jsx: 'automatic' }, optimizeDeps: { include: ['react', 'react-dom/client', 'react/jsx-runtime', 'react/jsx-dev-runtime', 'zod'] }, server: { host: '127.0.0.1', port: 0 }, appType: 'custom' });
  server.middlewares.use('/feedback-fixture', (_req, response) => { response.setHeader('Content-Type', 'text/html'); response.end('<div id="root"></div><script type="module" src="/src/ui/testing/ui-feedback.tsx"></script>'); });
  let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
  try {
    await server.listen(); browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1400, height: 900 } }); page.setDefaultTimeout(5000);
    const errors: string[] = []; page.on('pageerror', error => { errors.push(error.message); console.error(error.message); });
    await page.goto(`${server.resolvedUrls!.local[0]}feedback-fixture`);
    await page.getByRole('button', { name: 'UI comments', exact: true }).click();
    const bounds = (await page.locator('#send-action').boundingBox())!;
    await page.mouse.move(bounds.x + 10, bounds.y + 10);
    await page.locator('.ui-feedback-highlight').waitFor();
    await page.screenshot({ path: '/tmp/aegir-ui-feedback-select.png' });
    await page.mouse.click(bounds.x + 10, bounds.y + 10);
    await page.getByRole('dialog', { name: 'Leave a UI comment' }).waitFor();
    expect(await page.evaluate(() => (window as any).fixture.actions)).toBe(0);
    await page.getByRole('textbox', { name: 'Your comment' }).fill('Make this action clearer');
    await page.evaluate(() => { (window as any).fixture.fail = true; });
    await page.getByRole('button', { name: 'Save comment', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Could not save comment' }).waitFor();
    expect(await page.getByRole('textbox', { name: 'Your comment' }).inputValue()).toBe('Make this action clearer');
    await page.evaluate(() => { (window as any).fixture.fail = false; });
    await page.getByRole('button', { name: 'Save comment', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Comments (1)', exact: true }).click();
    await page.getByText('Make this action clearer', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Copy for Codex' }).click();
    expect(await page.evaluate(() => (window as any).fixture.copied)).toContain('#send-action');
    await page.getByRole('button', { name: 'Resolve', exact: true }).click();
    await page.getByText('No open comments.', { exact: false }).waitFor();
    await page.getByRole('button', { name: 'Resolved', exact: true }).click();
    await page.getByRole('button', { name: 'Reopen', exact: true }).click();
    await page.getByRole('button', { name: 'Open', exact: true }).click();
    await page.setViewportSize({ width: 950, height: 620 }); await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.screenshot({ path: '/tmp/aegir-ui-feedback-inbox.png' });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Comment on page' }).click();
    await page.getByRole('textbox', { name: 'Your comment' }).fill('Page comment');
    await page.screenshot({ path: '/tmp/aegir-ui-feedback-compose.png' });
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Select element', exact: true }).click();
    const field = (await page.getByRole('textbox', { name: 'Private field' }).boundingBox())!;
    await page.mouse.click(field.x + 10, field.y + 10);
    await page.getByRole('textbox', { name: 'Your comment' }).fill('Field comment');
    await page.getByRole('button', { name: 'Save comment', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    expect(await page.evaluate(() => JSON.stringify((window as any).fixture.state))).not.toContain('secret-value');
    await page.getByRole('button', { name: 'Exit UI comments' }).click();
    await page.locator('#send-action').click();
    expect(await page.evaluate(() => (window as any).fixture.actions)).toBe(2);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await server.close(); }
}, 60000);
